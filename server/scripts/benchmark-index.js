// Measures the inbox query before and after adding the composite index,
// prints a before/after table and writes it to docs/benchmark.md.
// Usage: npm run benchmark  (run `npm run db:reset` first so there are 100k emails)
//
// The index is left in place at the end, because the app should use it.
import fs from 'node:fs';
import { pool } from '../src/db.js';
import { buildListQuery } from '../src/routes/emails.js';

const RUNS = 5;
const INDEX_NAME = 'idx_emails_user_folder_created';
const DEMO_USER_ID = Number(process.env.DEMO_USER_ID);

// Exactly the query GET /api/emails runs for page 1 of the inbox.
const { listSql, listParams } = buildListQuery(DEMO_USER_ID, { folder: 'inbox', page: 1, limit: 20 });

function median(numbers) {
  const sorted = [...numbers].sort((a, b) => a - b);
  return sorted[Math.floor(sorted.length / 2)];
}

// EXPLAIN ANALYZE really runs the query and reports how long it took inside
// Postgres. That excludes network time, so the numbers measure the database alone.
async function explain() {
  const result = await pool.query(`EXPLAIN (ANALYZE, BUFFERS) ${listSql}`, listParams);
  const plan = result.rows.map((row) => row['QUERY PLAN']).join('\n');
  const ms = Number(plan.match(/Execution Time: ([\d.]+) ms/)[1]);
  return { ms, plan };
}

async function measure(label) {
  const times = [];
  let plan = '';
  for (let i = 1; i <= RUNS; i++) {
    const run = await explain();
    times.push(run.ms);
    plan = run.plan;
    console.log(`  ${label} run ${i}: ${run.ms.toFixed(3)} ms`);
  }
  return { times, median: median(times), plan };
}

function describePlan(plan) {
  return {
    seqScan: plan.includes('Seq Scan'),
    indexScan: plan.includes(`Index Scan using ${INDEX_NAME}`),
    sort: plan.includes('Sort Key'), // every Sort node prints a "Sort Key:" line
  };
}

async function main() {
  const counts = await pool.query(
    `SELECT count(*)::int AS total,
            count(*) FILTER (WHERE user_id = $1 AND folder = 'inbox')::int AS demo_inbox
     FROM emails`,
    [DEMO_USER_ID]
  );
  const { total, demo_inbox: demoInbox } = counts.rows[0];
  const version = (await pool.query('SHOW server_version')).rows[0].server_version;
  console.log(`emails: ${total.toLocaleString()}, demo user's inbox: ${demoInbox.toLocaleString()}\n`);

  // 1. Start without the index. ANALYZE refreshes the planner's statistics so
  //    the "before" run is a fair comparison, not slowed down by stale stats.
  await pool.query(`DROP INDEX IF EXISTS ${INDEX_NAME}`);
  await pool.query('ANALYZE emails');

  // 2. Measure without the index.
  console.log('Without index:');
  const before = await measure('before');

  // 3. Add the index. Equality columns (user_id, folder) first, the sort column
  //    (created_at DESC) last, so Postgres can read the newest 20 rows in order.
  await pool.query(`CREATE INDEX ${INDEX_NAME} ON emails (user_id, folder, created_at DESC)`);
  await pool.query('ANALYZE emails');

  // 4. Measure again with the index.
  console.log('\nWith index:');
  const after = await measure('after');

  // 5. Report.
  const beforePlan = describePlan(before.plan);
  const afterPlan = describePlan(after.plan);
  const speedup = before.median / after.median;
  const yesNo = (value) => (value ? 'yes' : 'no');

  const table = [
    '| | Without index | With index |',
    '|---|---|---|',
    `| Median execution time (${RUNS} runs) | ${before.median.toFixed(3)} ms | ${after.median.toFixed(3)} ms |`,
    `| All runs (ms) | ${before.times.map((t) => t.toFixed(3)).join(', ')} | ${after.times.map((t) => t.toFixed(3)).join(', ')} |`,
    `| Seq Scan on emails | ${yesNo(beforePlan.seqScan)} | ${yesNo(afterPlan.seqScan)} |`,
    `| Index Scan using ${INDEX_NAME} | ${yesNo(beforePlan.indexScan)} | ${yesNo(afterPlan.indexScan)} |`,
    `| Separate Sort step | ${yesNo(beforePlan.sort)} | ${yesNo(afterPlan.sort)} |`,
  ].join('\n');

  const planChanged = beforePlan.seqScan && !afterPlan.seqScan && afterPlan.indexScan;
  const summary = `Median went from ${before.median.toFixed(3)} ms to ${after.median.toFixed(3)} ms (${speedup.toFixed(0)}x faster). Plan changed from Seq Scan to Index Scan: ${planChanged ? 'yes' : 'no'}.`;

  console.log(`\n${table}\n\n${summary}`);

  const markdown = `# Inbox query index benchmark

Generated by \`npm run benchmark\` (server/scripts/benchmark-index.js) on ${new Date().toISOString().slice(0, 10)}.

**Data:** ${total.toLocaleString()} emails in total; the demo user (id ${DEMO_USER_ID}) has ${demoInbox.toLocaleString()} in their inbox. PostgreSQL ${version} on Neon.

**Query** (the exact SQL \`GET /api/emails\` runs for page 1 of the inbox, built by \`buildListQuery\`):

\`\`\`sql
${listSql.trim().replace(/\n\s+/g, '\n')}
-- params: ${JSON.stringify(listParams)}
\`\`\`

**Index:**

\`\`\`sql
CREATE INDEX ${INDEX_NAME} ON emails (user_id, folder, created_at DESC);
\`\`\`

## Results

${table}

${summary}

Times are Postgres's own \`Execution Time\` from \`EXPLAIN (ANALYZE, BUFFERS)\`, so they don't include network latency. The median of ${RUNS} runs is used so a single slow (cold-cache) run doesn't skew the result.

## Why the column order is (user_id, folder, created_at)

An index is like a phone book: sorted by the first column, then the second, then the third.

- **user_id and folder come first because the query tests them with \`=\`.** All of one user's inbox emails sit next to each other in the index, so Postgres jumps straight to that block instead of reading the whole table.
- **created_at DESC comes last because it's the sort column.** Inside that block the entries are already in newest-first order, so Postgres reads the first 20 and stops. There's no Sort step and no need to look at the user's other emails.
- **The wrong order would not work as well.** With \`(created_at, user_id, folder)\`, one user's inbox would be scattered across the whole index. Postgres would have to walk through everyone's emails by date and throw away the ones that aren't this user's.

## Query plan without the index

\`\`\`
${before.plan}
\`\`\`

## Query plan with the index

\`\`\`
${after.plan}
\`\`\`
`;

  const docsDir = new URL('../../docs/', import.meta.url);
  fs.mkdirSync(docsDir, { recursive: true });
  fs.writeFileSync(new URL('benchmark.md', docsDir), markdown);
  console.log('\nWrote docs/benchmark.md');
}

main()
  .catch((err) => {
    console.error('Benchmark failed:', err);
    process.exitCode = 1;
  })
  .finally(() => pool.end());
